/**
 * Country list for booking selects with localized labels and stable English values.
 */
function ipro_booking_v3_localized_countries(): array {
  $raw = require __DIR__ . '/booking-v3-countries.php';
  return array_map(
    static function ( array $country ): array {
      return [
        'value' => $country['name'],
        'name'  => __( $country['name'], 'hello-elementor' ),
        'code'  => $country['code'],
        'flag'  => $country['flag'],
      ];
    },
    $raw
  );
}

/**
 * Whether booking-V3 inline translations should apply (page or booking AJAX).
 */
function ipro_booking_v3_i18n_is_active(): bool {
  if (is_page_template('page-booking-v3.php') || is_page_template('page-booking-v4.php')) {
    return true;
  }
  if (wp_doing_ajax()) {
    $action = isset($_REQUEST['action']) ? sanitize_text_field(wp_unslash($_REQUEST['action'])) : '';
    if ($action === 'ipro_submit_booking') {
      return true;
    }
  }
  return false;
}

/**
 * Hooks into WordPress `gettext` to apply booking-V3 translations.
 * Runs only when the current domain is `hello-elementor` and we are on
 * the booking V3 page template, so performance impact is minimal.
 */
function ipro_booking_v3_lang_to_locale( string $lang_slug ): string {
  $lang_to_locale = [
    'en' => 'en_US', 'ru' => 'ru_RU', 'de' => 'de_DE',
    'fr' => 'fr_FR', 'es' => 'es_ES', 'it' => 'it_IT',
    'zh' => 'zh_CN', 'ar' => 'ar',
  ];
  return $lang_to_locale[ $lang_slug ] ?? 'en_US';
}

function ipro_booking_v3_get_active_locale(): string {
  if ( wp_doing_ajax() && isset( $_REQUEST['action'] ) && sanitize_text_field( wp_unslash( $_REQUEST['action'] ) ) === 'ipro_submit_booking' ) {
    $customer_lang = sanitize_text_field( wp_unslash( $_POST['locale'] ?? 'en' ) );
    return ipro_booking_v3_lang_to_locale( $customer_lang );
  }
  if ( function_exists( 'pll_current_language' ) ) {
    $pll_locale = pll_current_language( 'locale' );
    if ( is_string( $pll_locale ) && $pll_locale !== '' ) {
      return $pll_locale;
    }
    $pll_slug = pll_current_language( 'slug' );
    if ( is_string( $pll_slug ) && $pll_slug !== '' ) {
      return ipro_booking_v3_lang_to_locale( $pll_slug );
    }
  }
  return get_locale();
}

function ipro_booking_v3_apply_translations( string $translation, string $text, string $domain ): string {
  if ( $domain !== 'hello-elementor' ) return $translation;
  if ( ! ipro_booking_v3_i18n_is_active() ) return $translation;

  static $map = null;
  if ( $map === null ) {
    $map = ipro_booking_v3_i18n_map();
  }

  $locale = ipro_booking_v3_get_active_locale();
  if ( isset( $map[ $text ][ $locale ] ) ) {
    return $map[ $text ][ $locale ];
  }

  return $translation;
}
add_filter( 'gettext',              'ipro_booking_v3_apply_translations', 20, 3 );
add_filter( 'gettext_with_context', 'ipro_booking_v3_apply_translations', 20, 3 );
